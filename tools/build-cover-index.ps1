<#
.SYNOPSIS
    Builds a cover-hash index from the original launcher's app-state.json.

.DESCRIPTION
    The index contains only public metadata: installer UUID, game name, cover URL, and the
    SHA-256 of the cover image. It contains no image bytes and no account data.

    Use -InstalledOnly to index just the games installed under HKCU\Software\Legacy Games.
    This is the fast and recommended mode for a personal collection.

.EXAMPLE
    .\build-cover-index.ps1 -InstalledOnly

.EXAMPLE
    .\build-cover-index.ps1 -AppStatePath "D:\backup\app-state.json" -OutputPath ".\cover-index.json"
#>
param(
    [string]$AppStatePath = (Join-Path $env:APPDATA "legacy-games-launcher\app-state.json"),
    [string]$OutputPath = (Join-Path (Split-Path -Parent $PSScriptRoot) "src\LegacyShelf\Resources\cover-index.json"),
    [switch]$InstalledOnly,
    [int]$Limit = 0
)

$ErrorActionPreference = "Stop"

if (-not (Test-Path $AppStatePath)) {
    throw "app-state.json not found: $AppStatePath"
}

Write-Host "Reading catalog metadata…"
$json = Get-Content $AppStatePath -Raw -Encoding UTF8 | ConvertFrom-Json

# installer_uuid -> best catalog entry
$catalog = @{}
foreach ($product in $json.siteData.catalog) {
    if ($null -eq $product.games) { continue }
    foreach ($game in $product.games) {
        if ([string]::IsNullOrWhiteSpace($game.installer_uuid)) { continue }
        if ([string]::IsNullOrWhiteSpace($game.game_coverart)) { continue }

        $uuid = $game.installer_uuid.Trim()
        $name = ""
        if ($game.game_name) { $name = $game.game_name.Trim() }

        $candidate = [pscustomobject]@{
            uuid  = $uuid
            name  = $name
            url   = $game.game_coverart.Trim()
            score = $(if ($name) { 6 } else { 4 })
        }

        if (-not $catalog.ContainsKey($uuid) -or $candidate.score -gt $catalog[$uuid].score) {
            $catalog[$uuid] = $candidate
        }
    }
}

$selected = @()
if ($InstalledOnly) {
    $installed = @{}
    $registryRoot = "HKCU:\Software\Legacy Games"
    if (Test-Path $registryRoot) {
        Get-ChildItem $registryRoot | ForEach-Object {
            $value = (Get-ItemProperty $_.PSPath -ErrorAction SilentlyContinue).InstallerUUID
            if ($value) { $installed[$value.Trim()] = $true }
        }
    }

    Write-Host ("Installed UUIDs: {0}" -f $installed.Count)
    foreach ($uuid in $installed.Keys) {
        if ($catalog.ContainsKey($uuid)) { $selected += $catalog[$uuid] }
    }
}
else {
    $selected = @($catalog.Values)
}

$selected = @($selected | Sort-Object name)
if ($Limit -gt 0) { $selected = @($selected | Select-Object -First $Limit) }

Write-Host ("Fetching and hashing {0} cover(s)…" -f $selected.Count)
$covers = @()
$sha = [System.Security.Cryptography.SHA256]::Create()
$index = 0

foreach ($item in $selected) {
    $index++
    try {
        Write-Progress -Activity "Building cover index" -Status $item.name -PercentComplete (($index / [Math]::Max(1, $selected.Count)) * 100)

        $client = New-Object System.Net.WebClient
        $client.Headers.Add("User-Agent", "LegacyShelf/0.1 cover-index")
        try {
            $bytes = $client.DownloadData($item.url)
        }
        finally {
            $client.Dispose()
        }

        $hashBytes = $sha.ComputeHash($bytes)
        $hash = ([BitConverter]::ToString($hashBytes) -replace "-", "").ToLowerInvariant()

        $covers += [pscustomobject]@{
            uuid   = $item.uuid
            name   = $item.name
            url    = $item.url
            sha256 = $hash
        }
    }
    catch {
        Write-Warning ("Skipping {0}: {1}" -f $item.name, $_.Exception.Message)
    }
}
$sha.Dispose()
Write-Progress -Activity "Building cover index" -Completed

$document = [pscustomobject]@{
    version = 1
    source  = "legacygames.com catalog metadata; generated by tools/build-cover-index.ps1 (no image bytes)"
    covers  = @($covers)
}

$directory = Split-Path -Parent $OutputPath
if ($directory) { New-Item -ItemType Directory -Force $directory | Out-Null }
$document | ConvertTo-Json -Depth 6 | Set-Content -Path $OutputPath -Encoding UTF8

Write-Host ""
Write-Host ("Wrote {0} entries to {1}" -f $covers.Count, $OutputPath)
